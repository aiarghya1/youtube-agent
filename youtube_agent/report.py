def build_html(niches: list[NicheInsights]) -> str:
    return _TEMPLATE.render(
        niches=niches,
        date=datetime.now().strftime("%A, %d %B %Y"),
    )


def build_text(niches: list[NicheInsights]) -> str:
    lines = ["YouTube Niche Report", datetime.now().strftime("%A, %d %B %Y"), ""]
    for ins in niches:
        lines.append(f"=== {ins.niche.upper()} ({ins.total_creators} creators) ===")
        lines.append(
            f"Shorts avg views: {_fmt(ins.shorts_avg_views)} | "
            f"Long avg views: {_fmt(ins.long_avg_views)}"
        )
        if ins.hook_frequency:
            lines.append(
                "Hooks: " + ", ".join(f"{n} ({c})" for n, c in ins.hook_frequency)
            )
        lines.append("Top long-form:")
        for v in ins.top_long[:5]:
            lines.append(f"  - {v.title} [{_fmt(v.views)} views] {v.url}")
        lines.append("Top shorts:")
        for v in ins.top_shorts[:5]:
            lines.append(f"  - {v.title} [{_fmt(v.views)} views] {v.url}")
        if ins.llm_summary:
            lines.append("Why these work:")
            lines.append(ins.llm_summary)
        lines.append("")
    return "\n".join(lines)


def subject_line(niches: list[NicheInsights]) -> str:
    names = ", ".join(n.niche for n in niches)
    return f"📺 YouTube Report — {names} — {datetime.now():%d %b %Y}"
