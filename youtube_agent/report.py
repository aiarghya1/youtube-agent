"""Render analysis into an HTML email body (and a plain-text fallback)."""

from __future__ import annotations

from datetime import datetime

from jinja2 import Environment

from .analyzer import NicheInsights, detect_hooks

_ENV = Environment(autoescape=True)


def _fmt(n: float) -> str:
    n = int(n)
    if n >= 10_000_000:
        return f"{n / 10_000_000:.1f}Cr"  # crore, India-friendly
    if n >= 100_000:
        return f"{n / 100_000:.1f}L"  # lakh
    if n >= 1_000:
        return f"{n / 1_000:.1f}K"
    return str(n)


_ENV.filters["fmt"] = _fmt


def _hooks_filter(title: str) -> str:
    hooks = detect_hooks(title)
    return ", ".join(hooks) if hooks else "—"


_ENV.filters["hooks"] = _hooks_filter

